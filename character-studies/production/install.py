"""Install the current packed production candidate into the normal game build."""
import argparse
import hashlib
import json
from pathlib import Path
import shutil

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
PREFIX = "art/painted-two-body/"


def install(source):
    packet = (source / "movement.json").read_text(encoding="utf8").strip()
    data = json.loads(packet)
    files = {item["file"] for family in data["banks"].values() for item in family.values()}
    files.update(item["file"] for family in data["static"].values()
                 for state in family.values() for item in state.values())
    files.update(item["file"] for family in data["dolls"].values() for item in family)
    files.update(item["file"] for item in data["actionHeads"].values())
    target = ROOT / "game/art/painted-two-body"
    target.mkdir(parents=True, exist_ok=True)
    records = []
    for file in sorted(files):
        name = Path(file).name
        origin = source / name
        assert file == "painted-two-body/" + name and origin.is_file(), file
        shutil.copyfile(origin, target / name)
        content = origin.read_bytes()
        records.append(dict(path=PREFIX + name, size=len(content), sha256=hashlib.sha256(content).hexdigest()))
    known = {item["path"].removeprefix(PREFIX) for item in records}
    for stale in target.glob("*.webp"):
        if stale.name not in known:
            stale.unlink()
    coordinates = ROOT / "game/src/artpaintedtwo.js"
    coordinates.write_text("/* Generated by character-studies/production/pack-movement.py. */\n"
                           "ArtData.twoBodyMovement = " + packet + ";\n", encoding="utf8", newline="\n")
    manifest = ROOT / "arttools/packed_manifest.json"
    current = json.loads(manifest.read_text(encoding="utf8"))
    other = [item for item in current if not item["path"].startswith(PREFIX)]
    revised = sorted(other + records, key=lambda item: item["path"])
    manifest.write_text(json.dumps(revised, indent=2) + "\n", encoding="utf8", newline="\n")
    print(f"Installed {len(records)} new paint and mask pages with their exact hashes.")


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("packed", type=Path)
    install(parser.parse_args().packed)
