"""Pack the reviewed, built-in generated complete paper-doll heads."""

import argparse
import hashlib
import io
import json
from pathlib import Path

from PIL import Image


ROOT = Path(__file__).resolve().parents[1]
INPUTS = Path(__file__).with_name("head_art_inputs.json")
SOURCE_SIZE = (1536, 1024)
COLS = 4
ROWS = 3


def digest(data):
    return hashlib.sha256(data).hexdigest()


def pack(raw_dir, source, scale):
    raw = (raw_dir / source["filename"]).read_bytes()
    if digest(raw) != source["sha256"]:
        raise ValueError(f'Source hash differs for {source["filename"]}')
    image = Image.open(io.BytesIO(raw))
    if image.mode != "RGBA" or image.size != SOURCE_SIZE:
        raise ValueError(f'Expected a transparent {SOURCE_SIZE} sheet for body {source["body"]}')
    if len(source["styles"]) != COLS * ROWS:
        raise ValueError("Expected twelve named styles per body")

    alpha = image.getchannel("A").point(lambda a: round(max(0, a - 7) * 255 / 247))
    image.putalpha(alpha)
    image = image.resize(tuple(round(side * scale) for side in SOURCE_SIZE), Image.Resampling.LANCZOS)
    image.putalpha(image.getchannel("A").point(lambda a: a if a >= 3 else 0))
    styles = []
    for i, (style, name, hair, beard) in enumerate(source["styles"]):
        row, col = divmod(i, COLS)
        cell_width = image.width // COLS
        x = col * cell_width
        y, bottom = (round(top * scale) for top in source["rows"][row:row + 2])
        cell = image.getchannel("A").crop((x, y, x + cell_width, bottom))
        bbox = cell.getbbox()
        if not bbox or min(bbox[0], bbox[1], cell.width - bbox[2], cell.height - bbox[3]) < 2:
            raise ValueError(f"Head {style} is missing or touches its cell boundary: {bbox}")
        l, t, r, b = bbox
        eye = source["eyeLines"][row]
        styles.append({
            "id": style, "name": name, "hair": hair, "beard": beard,
            "rect": [x + l - 1, y + t - 1, r - l + 2, b - t + 2],
            "anchor": [round((col * SOURCE_SIZE[0] / COLS + SOURCE_SIZE[0] / COLS / 2) * scale, 3),
                       round((eye - 110) * scale, 3), round(source["faceWidth"] * scale, 3),
                       round(source["heightUnit"] * scale, 3)],
        })
    packed = io.BytesIO()
    image.save(packed, format="WEBP", lossless=True, method=6, exact=False)
    return packed.getvalue(), styles


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--raw-dir", type=Path, default=ROOT / "work" / "head-art-2026-11-25")
    parser.add_argument("--check", action="store_true", help="Repack in memory and compare to the tracked files")
    args = parser.parse_args()
    receipt = json.loads(INPUTS.read_text(encoding="utf-8"))
    data = []
    outputs = {}
    for index, source in enumerate(receipt["sources"]):
        if index != source["body"]:
            raise ValueError("Body styles must be ordered by the saved body index")
        content, styles = pack(args.raw_dir, source, receipt["atlasScale"])
        atlas = f'heads/{source["output"]}'
        outputs[ROOT / "game" / "art" / atlas] = content
        data.append({"atlas": atlas, "styles": styles})
        print(f'{atlas}: {len(styles)} heads, {len(content):,} bytes, SHA-256 {digest(content)}')
    js = "/* Generated by arttools/head_art.py. */\nconst ArtHeads = " + json.dumps(data, ensure_ascii=True, separators=(",", ":")) + ";\n"
    js += "if (typeof module !== 'undefined' && module.exports) module.exports = ArtHeads;\n"
    outputs[ROOT / "game" / "src" / "artheads.js"] = js.encode("utf-8")
    for path, content in outputs.items():
        if args.check:
            if path.read_bytes() != content:
                raise ValueError(f"Packed result differs: {path.relative_to(ROOT)}")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(content)


if __name__ == "__main__":
    main()
