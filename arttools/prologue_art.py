"""Pack the reviewed Marigold hull with Pillow 12.0.0.

Place the original PNG in --raw-dir and leave its filename intact. Normal
replays check the source and generated bytes against --inputs. Use --record
after reviewing replacement art.
"""

import argparse
import hashlib
from io import BytesIO
import json
from pathlib import Path
from tempfile import NamedTemporaryFile

from PIL import Image, __version__ as pillow_version, features


ROOT = Path(__file__).resolve().parents[1]
SOURCE = "exec-35394218-af15-4ec0-a9a2-cb8ce3c79d9b.png"
PILLOW = "12.0.0"
ALPHA_THRESHOLD = 128
CROP_MARGIN = 6
WIDTH = 480
WEBP_OPTIONS = {"quality": 90, "method": 6}


def sha256(data):
    return hashlib.sha256(data).hexdigest()


def pack(raw_dir, approved):
    if pillow_version != PILLOW:
        raise ValueError(f"Packing requires Pillow {PILLOW}; found {pillow_version}.")
    source = raw_dir / SOURCE
    raw = source.read_bytes()
    digest = sha256(raw)
    if approved is not None:
        approved_source = approved.get("source")
        if not isinstance(approved_source, dict) or approved_source.get("sha256") != digest:
            raise ValueError(f"Source hash does not match the approved receipt: {SOURCE}")

    with Image.open(BytesIO(raw)) as base:
        if base.format != "PNG" or base.mode != "RGBA":
            raise ValueError(f"Expected a PNG with RGBA channels: {SOURCE}")
        size = base.size
        support = base.getchannel("A").point(lambda value: 255 if value >= ALPHA_THRESHOLD else 0).getbbox()
        if support is None:
            raise ValueError("The hull has no pixels at or above the crop alpha threshold.")
        left, top, right, bottom = support
        crop = (
            max(0, left - CROP_MARGIN), max(0, top - CROP_MARGIN),
            min(size[0], right + CROP_MARGIN), min(size[1], bottom + CROP_MARGIN),
        )
        cropped = base.crop(crop)
        height = round(cropped.height * WIDTH / cropped.width)
        hull = cropped.resize((WIDTH, height), Image.Resampling.LANCZOS)

    encoded = BytesIO()
    hull.save(encoded, format="WEBP", **WEBP_OPTIONS)
    webp = encoded.getvalue()
    geometry = {"image": "ship/deck.webp", "width": WIDTH, "height": height}
    script = (
        "/* Generated by arttools/prologue_art.py. Dimensions are in high-resolution pixels. */\n"
        "const ShipArt = " + json.dumps(geometry, separators=(",", ":")) + ";\n"
    ).encode("utf-8")
    receipt = {
        "schema": 1,
        "source": {
            "filename": SOURCE, "sha256": digest, "dimensions": list(size),
            "alpha_threshold": ALPHA_THRESHOLD, "alpha_bounds": list(support),
            "crop_margin": CROP_MARGIN, "crop": list(crop),
        },
        "packing": {
            "pillow": pillow_version, "libwebp": features.version("webp"),
            "resampling": "LANCZOS", "webp": WEBP_OPTIONS,
        },
        "outputs": {
            "deck.webp": {"sha256": sha256(webp), "size": len(webp), "dimensions": list(hull.size)},
            "artship.js": {"sha256": sha256(script), "size": len(script)},
        },
    }
    if approved is not None and receipt != approved:
        raise ValueError("The packed hull or its geometry differs from the approved receipt.")
    return webp, script, receipt


def write_outputs(outputs):
    staged = []
    try:
        for path, contents in outputs.items():
            path.parent.mkdir(parents=True, exist_ok=True)
            with NamedTemporaryFile(dir=path.parent, prefix=".prologue-art-", delete=False) as file:
                staged.append((Path(file.name), path))
                file.write(contents)
        for temp, path in staged:
            temp.replace(path)
    finally:
        for temp, _ in staged:
            temp.unlink(missing_ok=True)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--raw-dir", required=True, type=Path)
    parser.add_argument("--out-dir", type=Path, default=ROOT / "game/art/ship")
    parser.add_argument("--js", type=Path, default=ROOT / "game/src/artship.js")
    parser.add_argument("--inputs", type=Path, default=ROOT / "arttools/prologue_art_inputs.json")
    parser.add_argument("--record", action="store_true")
    args = parser.parse_args()
    deck = args.out_dir / "deck.webp"
    destinations = {path.resolve() for path in (deck, args.js, args.inputs)}
    if len(destinations) != 3 or any(path.is_relative_to(args.raw_dir.resolve()) for path in destinations):
        parser.error("Output and receipt paths must be distinct and outside the raw source folder.")
    try:
        approved = None if args.record else json.loads(args.inputs.read_text(encoding="utf-8"))
        if not args.record and not isinstance(approved, dict):
            raise ValueError("Expected a source receipt object.")
        webp, script, receipt = pack(args.raw_dir, approved)
        outputs = {deck: webp, args.js: script}
        if args.record:
            outputs[args.inputs] = (json.dumps(receipt, indent=2) + "\n").encode("utf-8")
        write_outputs(outputs)
    except (OSError, ValueError) as error:
        parser.exit(1, f"{error}\n")
    print("Packed the Marigold hull.")


if __name__ == "__main__":
    main()
