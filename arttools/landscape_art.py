"""Pack new-only regional vegetation from immutable built-in source sheets.

Record source hashes/crops once after review; replay validates all inputs before writing.
"""
import argparse
import hashlib
import json
from pathlib import Path
import numpy as np
from PIL import Image
from scipy import ndimage

ROOT = Path(__file__).resolve().parents[1]
RECEIPT = ROOT / 'arttools/landscape_inputs.json'
NAMES = [f'tree{i}' for i in range(8)] + [f'detail{i}' for i in range(8)]
HEIGHTS = [35, 57, 79, 94, 33, 55, 76, 90, 17, 17, 19, 13, 7, 10, 13, 15]

def sha(p):
    return hashlib.sha256(p.read_bytes()).hexdigest()

def boxes(im):
    a = np.asarray(im)[:, :, 3]
    labels, _ = ndimage.label(ndimage.binary_dilation(a > 150, iterations=2))
    groups = {}
    for label, sl in enumerate(ndimage.find_objects(labels), 1):
        if sl is None:
            continue
        mask = (labels[sl] == label) & (a[sl] > 150)
        area = int(mask.sum())
        if area < 180:
            continue
        ys, xs = np.nonzero(mask)
        cx, cy = float(xs.mean()) + sl[1].start, float(ys.mean()) + sl[0].start
        index = min(3, int(cy*4/im.height))*4 + min(3, int(cx*4/im.width))
        box = [sl[1].start, sl[0].start, sl[1].stop, sl[0].stop]
        if index in groups:
            old = groups[index]
            box = [min(old[0],box[0]),min(old[1],box[1]),max(old[2],box[2]),max(old[3],box[3])]
        groups[index] = box
    if set(groups) != set(range(16)):
        raise ValueError('Missing vegetation cells: '+str(set(range(16))-set(groups)))
    return {name:groups[i] for i,name in enumerate(NAMES)}

def clean(piece):
    a = np.array(piece)
    alpha = a[:, :, 3]
    core = ndimage.binary_erosion(alpha > 220, iterations=1)
    if not core.any():
        raise ValueError('No opaque vegetation interior')
    # Transparent matte colours are not foliage. Carry real interior colours
    # into the semitransparent fringe while preserving its coverage.
    yy, xx = ndimage.distance_transform_edt(~core, return_distances=False, return_indices=True)
    fringe = ~core
    a[fringe, :3] = a[yy[fringe], xx[fringe], :3]
    a[alpha < 80, 3] = 0
    return Image.fromarray(a)

def main():
    p = argparse.ArgumentParser()
    p.add_argument('--raw-dir', required=True, type=Path)
    p.add_argument('--record', action='store_true')
    p.add_argument('--review-dir', type=Path)
    args = p.parse_args()
    if args.record:
        receipt = {'recipe':1,'regions':{}}
        index = json.loads((args.raw_dir/'sources.json').read_text())
        for r in range(1,9):
            src = args.raw_dir/index[str(r)]
            im = Image.open(src).convert('RGBA')
            receipt['regions'][str(r)] = {'file':src.name,'sha256':sha(src),'size':list(im.size),'crops':boxes(im)}
    else:
        receipt = json.loads(RECEIPT.read_text())
    sources = {}
    for r, spec in receipt['regions'].items():
        src = args.raw_dir/spec['file']
        if sha(src) != spec['sha256']:
            raise ValueError('Source changed: '+str(src))
        sources[int(r)] = Image.open(src).convert('RGBA')
    outputs, tables = [], {}
    for r, im in sources.items():
        spec = receipt['regions'][str(r)]
        atlas = Image.new('RGBA',(1024,1024))
        coords = {}
        x = y = row_h = 2
        for index, name in enumerate(NAMES):
            piece = clean(im.crop(spec['crops'][name]))
            h = round(HEIGHTS[index]*3*(.85 if r == 6 and index < 4 else 1))
            w = round(piece.width*h/piece.height)
            if w > 320:
                h = round(h*320/w);w = 320
            piece = piece.resize((w,h),Image.Resampling.LANCZOS)
            if x+w+2 > atlas.width:
                x=2;y+=row_h+4;row_h=0
            if y+h+2 > atlas.height:
                raise ValueError('Vegetation atlas overflow')
            atlas.alpha_composite(piece,(x,y));coords[name]=[x,y,w,h]
            if args.review_dir:
                folder=args.review_dir/str(r);folder.mkdir(parents=True,exist_ok=True)
                piece.save(folder/(name+'.png'))
            x+=w+4;row_h=max(row_h,h)
        atlas = atlas.crop((0,0,1024,y+row_h+2))
        out = ROOT/f'game/art/landscape/region-{r}.webp'
        out.parent.mkdir(parents=True,exist_ok=True)
        atlas.save(out,'WEBP',lossless=True,method=6)
        outputs.append({'path':'art/landscape/'+out.name,'size':out.stat().st_size,'sha256':sha(out),'dimensions':list(atlas.size)})
        tables[r] = coords
    js = '/* Generated by arttools/landscape_art.py; do not edit. */\nconst LandscapeArt = '+json.dumps({'files':[f'landscape/region-{r}.webp' for r in range(1,9)],'at':tables},separators=(',',':'))+';\n'
    (ROOT/'game/src/artlandscape.js').write_text(js,encoding='utf-8')
    manifest_path = ROOT/'arttools/packed_manifest.json'
    manifest = json.loads(manifest_path.read_text())
    prior = [x for x in manifest if not x['path'].startswith('art/landscape/')]
    manifest_path.write_text(json.dumps(prior+outputs,indent=2)+'\n',encoding='utf-8')
    if args.record:
        RECEIPT.write_text(json.dumps(receipt,indent=2)+'\n',encoding='utf-8')
    print(f'Packed {len(tables)*16} vegetation pieces; {sum(o["size"] for o in outputs):,} bytes; old records unchanged.')

if __name__ == '__main__':
    main()
