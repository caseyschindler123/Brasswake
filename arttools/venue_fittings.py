"""Pack the approved painted stable and casino fixtures into a transparent atlas."""

import argparse
from hashlib import sha256
from io import BytesIO
import json
from pathlib import Path

from PIL import Image, ImageDraw, __version__ as pillow_version


ROOT = Path(__file__).resolve().parents[1]
RECEIPT = ROOT / "arttools/venue_fittings_inputs.json"
ART = ROOT / "game/art/venues/fittings.webp"
JS = ROOT / "game/src/artvenues.js"
HI_RES = 3
GUTTER = 2


def clean(piece, cutoff):
    piece.putalpha(piece.getchannel("A").point(lambda alpha: alpha if alpha > cutoff else 0))
    alpha_bounds = piece.getchannel("A").getbbox()
    if not alpha_bounds:
        raise ValueError("A fixture crop contains no visible pixels")
    return piece.crop(alpha_bounds)


def pack(raw, settings):
    cell_w, cell_h = settings["cell"]
    atlas = Image.new("RGBA", (cell_w * 4, cell_h * 3))
    contact = Image.new("RGB", (4 * 220, 3 * 196), "#ada994")
    draw = ImageDraw.Draw(contact)
    rects = {}
    for i, (name, spec) in enumerate(settings["pieces"].items()):
        col, row = i % 4, i // 4
        piece = clean(raw.crop(spec["crop"]), settings["alpha_cutoff"])
        max_width, max_height = (n * HI_RES for n in spec["bounds"])
        scale = min(max_width / piece.width, max_height / piece.height)
        size = (round(piece.width * scale), round(piece.height * scale))
        if size[0] > cell_w - GUTTER * 2 or size[1] > cell_h - GUTTER * 2:
            raise ValueError(f"{name} overflows the assigned atlas cell")
        piece = piece.resize(size, Image.Resampling.LANCZOS)
        x = col * cell_w + (cell_w - size[0]) // 2
        y = row * cell_h + (cell_h - size[1]) // 2
        atlas.paste(piece, (x, y))
        rects[name] = [x, y, *size]
        base_x, base_y = col * 220, row * 196
        draw.rectangle((base_x + 4, base_y + 4, base_x + 215, base_y + 170), fill="#172324" if i % 2 else "#d1bf96")
        contact.paste(piece, (base_x + (220 - piece.width) // 2, base_y + (172 - piece.height) // 2), piece)
        draw.text((base_x + 10, base_y + 178), name.removeprefix("venue_").replace("_", " "), fill="#161a18")

    encoded = BytesIO()
    atlas.save(encoded, format="WEBP", lossless=True, quality=85, method=6)
    metadata = {"image": "venues/fittings.webp", "at": rects}
    script = ("/* Generated by arttools/venue_fittings.py. Atlas bounds are in high-resolution pixels. */\n"
              "const VenueArt = " + json.dumps(metadata, separators=(",", ":")) + ";\n").encode()
    return {ART: encoded.getvalue(), JS: script}, contact


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--raw-dir", required=True, type=Path)
    parser.add_argument("--contact", type=Path)
    parser.add_argument("--check", action="store_true", help="Compare a clean replay with the tracked outputs.")
    args = parser.parse_args()
    settings = json.loads(RECEIPT.read_text(encoding="utf-8"))
    original = settings["source"]
    data = (args.raw_dir / original["filename"]).read_bytes()
    if sha256(data).hexdigest() != original["sha256"]:
        raise ValueError("The fixture source hash differs from its receipt")
    if pillow_version != settings["pillow"]:
        raise ValueError("Use the pinned Pillow version in the fixture receipt")
    with Image.open(BytesIO(data)) as raw:
        if raw.format != "PNG" or raw.mode != "RGBA" or list(raw.size) != original["dimensions"]:
            raise ValueError("The fixture source dimensions or channels differ from its receipt")
        outputs, contact = pack(raw, settings)
    for destination, expected in outputs.items():
        if args.check:
            if destination.read_bytes() != expected:
                raise ValueError(f"Packing replay differs from {destination.name}")
        else:
            destination.parent.mkdir(parents=True, exist_ok=True)
            destination.write_bytes(expected)
        print(f"{destination.relative_to(ROOT)} {len(expected)} bytes {sha256(expected).hexdigest()}")
    if args.contact:
        args.contact.parent.mkdir(parents=True, exist_ok=True)
        contact.save(args.contact)


if __name__ == "__main__":
    main()
