"""Pack the building-kit interior art into game/art/kit/k1.webp and src/artkit.js.

Usage: python3 -I arttools/kit_pack.py <raw dir> [<raw dir> ...]
Reads KT02, KT04-06, KF01 and KW01 (any of the dirs; first match wins).
Textures are cropped to their repeat and cross-faded at the edges so they tile.
Furniture and wall pieces are cut by shape, grouped by grid cell, and scaled to
game size (48 hi-res px per tile). Coordinates are hi-res px in the atlas.
"""
import sys, os, json
from pathlib import Path
import numpy as np
from PIL import Image
from scipy import ndimage

sys.path.insert(0, str(Path(__file__).resolve().parent))
from art_paths import ART, directory, javascript, sheet_paths
OUT = directory('BW_OUT', ART); JS = javascript('BW_KIT_JS', 'artkit.js')
dirs = sys.argv[1:]
INPUTS = {}
for source in dirs:
    for name, path in sheet_paths(source).items(): INPUTS.setdefault(name, path)


def find(name):
    if name in INPUTS: return INPUTS[name]
    sys.exit('missing ' + name)


def xfade(y, k, axis):
    n = y.shape[axis]; t = np.linspace(0, 1, k)
    if axis == 1:
        w = t[None, :, None]; y2 = y[:, :n - k].copy(); y2[:, :k] = y[:, n - k:] * (1 - w) + y[:, :k] * w
    else:
        w = t[:, None, None]; y2 = y[:n - k].copy(); y2[:k] = y[n - k:] * (1 - w) + y[:k] * w
    return y2


def best_end(x, axis):
    n = x.shape[axis]; best = (1e9, n)
    for e in range(int(n * .8), n):
        a = x[:, 0] if axis == 1 else x[0]; b = x[:, e] if axis == 1 else x[e]
        s = np.abs(a - b).mean()
        if s < best[0]: best = (s, e)
    return best[1]


def texture(name, scale, box=None, k=48, wrap_y=True):
    im = Image.open(find(name)).convert('RGB'); x = np.array(im).astype(float)
    if box is None:
        box = (0, 0, best_end(x, 1), best_end(x, 0) if wrap_y else x.shape[0])
    y = x[box[1]:box[3], box[0]:box[2]]
    y = xfade(y, k, 1)
    if wrap_y: y = xfade(y, k, 0)
    t = Image.fromarray(y.clip(0, 255).astype('uint8'))
    return t.resize((round(t.width * scale), round(t.height * scale)), Image.LANCZOS).convert('RGBA')


def pieces(name):
    im = Image.open(find(name)).convert('RGBA'); a = np.array(im)
    al = a[..., 3].copy(); al[al < 60] = 0; al[al >= 200] = 255; a[..., 3] = al; im = Image.fromarray(a)
    lab, n = ndimage.label(ndimage.binary_dilation(al >= 200, iterations=6))
    cells = {}
    for i, sl in enumerate(ndimage.find_objects(lab)):
        h, w = sl[0].stop - sl[0].start, sl[1].stop - sl[1].start
        if h * w < 2500: continue
        cy, cx = (sl[0].start + sl[0].stop) / 2, (sl[1].start + sl[1].stop) / 2
        key = (int(cy // 256), int(cx // 256))
        b = cells.get(key)
        cells[key] = (sl[0].start, sl[0].stop, sl[1].start, sl[1].stop) if b is None else (min(b[0], sl[0].start), max(b[1], sl[0].stop), min(b[2], sl[1].start), max(b[3], sl[1].stop))
    out = {}
    for (r, c), b in cells.items():
        out[r * 4 + c] = im.crop((b[2], b[0], b[3], b[1]))
    return out


# --- textures (hi-res px; one tile = 48) ---
TEX = {
    'floor': texture('KT05', .16),
    'flag': texture('KT06', .16),
    'wall': texture('KT04', .20, box=(54, 28, 972, 999), k=16),
    'stone': texture('KT02', .13),
}
# --- furniture KF01, by grid index row*4+col, with game scale ---
FN = ['bar', 'barend', 'rtable', 'ltable', 'stool', 'bench', 'hearth', 'kegs', 'shelf', 'counter', 'bankctr', 'strongbox', 'bed', 'chest', 'rug', 'cupboard']
FS = {'hearth': .36, 'rug': .40, 'kegs': .31, 'shelf': .30, 'cupboard': .30, 'bed': .32}
WN = ['window', 'widewin', 'doorway', 'lamp', 'banner', 'wshelf', 'painting', 'pots', 'weapons', 'antlers', 'board', 'herbs', 'coat', 'curtain', 'candles', 'mirror']
items = []
for i, p in pieces('KF01').items():
    s = FS.get(FN[i], .33); items.append(('f_' + FN[i], p.resize((round(p.width * s), round(p.height * s)), Image.LANCZOS)))
for i, p in pieces('KW01').items():
    s = .26; items.append(('w_' + WN[i], p.resize((round(p.width * s), round(p.height * s)), Image.LANCZOS)))
for k, t in TEX.items(): items.append(('t_' + k, t))

# --- shelf-pack into one atlas, 1024 wide ---
items.sort(key=lambda kv: -kv[1].height)
W, x, y, rh, rects = 1024, 0, 0, 0, {}
for name, im in items:
    if x + im.width > W: x, y, rh = 0, y + rh + 2, 0
    rects[name] = [x, y, im.width, im.height]; x += im.width + 2; rh = max(rh, im.height)
H = y + rh
atlas = Image.new('RGBA', (W, H))
for name, im in items:
    r = rects[name]; atlas.paste(im, (r[0], r[1]))
os.makedirs(OUT + 'kit', exist_ok=True)
atlas.save(OUT + 'kit/k1.webp', 'WEBP', quality=88, method=6)
with open(JS, 'w', encoding='utf-8', newline='\n') as f:
    f.write('/* generated by kit_pack.py: building-kit interiors, hi-res px in art/kit/k1.webp */\n')
    f.write('if (typeof ArtData !== "undefined") ArtData.kit = ' + json.dumps({'k1': rects}, separators=(',', ':')) + ';\n')
print('atlas', W, H, 'pieces', len(rects), 'bytes', os.path.getsize(OUT + 'kit/k1.webp'))
