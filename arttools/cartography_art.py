"""Pack approved transparent cartography sheets into the game asset atlases.

Normal rebuilds verify the approved source receipt. Pass --record after visual
review to record a new source set. Alternate atlas and JS destinations allow
an independent byte-for-byte replay check.
"""

import argparse
from io import BytesIO
import json
from pathlib import Path
import sys


sys.path.insert(0, str(Path(__file__).resolve().parent))
from dungeon_art import isolate_sprites
from world_art import make_atlas, open_sheet, resize, write_outputs


ROOT = Path(__file__).resolve().parents[1]
# Maximum packed width and height in hi-res pixels, in source cell order.
PROPS = (
    ('chart_counter', 143), ('scroll_rack', 135), ('map_cabinet', 131), ('compass_sign', 75),
    ('desk_compass', 47), ('rolled_maps', 50), ('survey_instruments', 59), ('mapmaker_stool', 62),
    ('ink_parchment', 54), ('wall_chart', 108), ('lantern', 67), ('celestial_instrument', 70),
    ('road_sign', 100), ('road_left', 77), ('road_right', 77), ('road_up', 66),
)
ATLAS = (('grand_atlas', 288), ('atlas_case', 124), ('atlas_closed', 155), ('atlas_icon', 64))
REGIONAL = tuple((f'wall_chart_{region}', 108) for region in range(1, 9)) + tuple(
    (f'chart_supply_{region}', 63) for region in range(1, 9))
SHEETS = {'CA01': (4, 'props', PROPS), 'CA02': (2, 'atlas', ATLAS), 'CA03': (4, 'regional', REGIONAL)}


def pack(raw_dir, recorded):
    paths = {name: raw_dir / f'{name}.png' for name in SHEETS}
    missing = [path.name for path in paths.values() if not path.is_file()]
    if missing:
        raise ValueError('Missing required cartography sheets: ' + ', '.join(missing))
    receipt = {'schema': 1, 'alpha': {'discard_below': 60, 'opaque_from': 200}, 'sources': {}}
    coordinates = {'at': {}, 'files': []}
    atlases = {}
    for name, (columns, atlas_name, definitions) in SHEETS.items():
        image, record = open_sheet(paths[name], (1024, 1024), opaque=False)
        tiles = {}
        for cell, ((key, cap), (box, sprite)) in enumerate(zip(definitions, isolate_sprites(image, columns, name))):
            scale = min(1, cap / max(sprite.size))
            tile = resize(sprite, scale)
            tiles[key] = tile
            record['pieces'][key] = {'cell': cell, 'crop': box, 'scale': scale, 'size': list(tile.size)}
        receipt['sources'][name] = record
        if recorded is not None and recorded.get('sources', {}).get(name) != record:
            raise ValueError(f'{name} does not match the approved source receipt')
        atlas, rects = make_atlas(tiles)
        filename = f'{atlas_name}.webp'
        path = f'cartography/{filename}'
        coordinates['files'].append(path)
        coordinates['at'].update({key: {'f': path, 'r': rects[key]} for key in tiles})
        stream = BytesIO()
        atlas.save(stream, format='WEBP', quality=90, method=4)
        atlases[filename] = stream.getvalue()
    if recorded is not None and recorded != receipt:
        raise ValueError('Cartography source receipt schema or sheet list differs')
    return coordinates, atlases, receipt


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--raw-dir', required=True, type=Path)
    parser.add_argument('--out-dir', type=Path, default=ROOT / 'game/art/cartography')
    parser.add_argument('--js', type=Path, default=ROOT / 'game/src/artcartography.js')
    parser.add_argument('--inputs', type=Path, default=ROOT / 'arttools/cartography_art_inputs.json')
    parser.add_argument('--record', action='store_true')
    args = parser.parse_args()
    paths = (args.out_dir, args.js, args.inputs)
    if any(path.resolve().is_relative_to(args.raw_dir.resolve()) for path in paths):
        parser.error('Output paths must be outside the raw source folder')
    try:
        recorded = None if args.record else json.loads(args.inputs.read_text(encoding='utf-8'))
        coordinates, atlases, receipt = pack(args.raw_dir, recorded)
        script = '/* Generated by arttools/cartography_art.py. Atlas rectangles are in hi-res pixels. */\n'
        script += 'const CartographyArt = ' + json.dumps(coordinates, separators=(',', ':')) + ';\n'
        outputs = {args.out_dir / filename: data for filename, data in atlases.items()}
        outputs[args.js] = script.encode('utf-8')
        if args.record:
            outputs[args.inputs] = (json.dumps(receipt, indent=2) + '\n').encode('utf-8')
        write_outputs(outputs)
    except (OSError, ValueError) as error:
        parser.exit(1, f'{error}\n')
    print(f'Packed {len(coordinates["at"])} cartography sprites into {len(atlases)} atlases.')


if __name__ == '__main__':
    main()
